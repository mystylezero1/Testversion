export const INITIAL_GUESTS: Guest[] = (() => {
  const list: Guest[] = [];
  INITIAL_TABLES.forEach((table) => {
    // Gather all seat numbers assigned to this table
    const tableSeats: number[] = [];
    if (table.topSeats) tableSeats.push(...table.topSeats);
    if (table.bottomSeats) tableSeats.push(...table.bottomSeats);
    if (table.leftSeats) tableSeats.push(...table.leftSeats);
    if (table.rightSeats) tableSeats.push(...table.rightSeats);

    tableSeats.forEach((seatNum, idx) => {
      const sample = GUEST_NAMES_SAMPLE[seatNum] || {
        name: `Gast #${seatNum}`,
        group: table.tag || 'Gäste',
      };
      list.push({
        id: `g-${seatNum}`,
        name: sample.name,
        tableId: table.id,
        tableName: table.name,
        seat: idx + 1,
        globalSeat: seatNum,
        role: sample.role || 'guest',
        group: sample.group,
        notes: sample.notes,
      });
    });
  });
  return list;
})();

